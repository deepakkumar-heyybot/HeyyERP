"""Preventive maintenance plans for machines and moulds (BRD FR-MNT-01).

A plan says "service this machine every N days" or "this mould every N shots" (shots only for
moulds). Nothing is generated by a timer: the schedule is worked out when it is asked for, from
when the plan was last done and, for moulds, the shots counted since. A plan is OVERDUE when its
date has passed or its shots are used up, DUE_SOON within `pmDueSoonDays` (a company rule) or the
last tenth of its shots, otherwise OK. Doing a plan records the work in the history and starts the
next interval from that moment. Mould shots are added as production runs; a mould past its shot
limit is flagged. Needs mnt to plan and record; counting shots needs mfg.entry; reading needs the
maintenance module.
"""

from datetime import UTC, datetime, timedelta
from typing import Any, Literal
from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException, Query, status
from pydantic import BaseModel, Field, model_validator

from heyyerp_api.business_rules import service as rules
from heyyerp_api.masters.common import (
    Ctx,
    Page,
    Paging,
    Strict,
    audit,
    not_found,
    one,
    require_in_scope,
    requires,
    requires_module,
    rows,
    scope_clause,
)

router = APIRouter(prefix="/maintenance", tags=["maintenance"])
manage = requires("mnt")
record_shots = requires("mfg.entry")
read = requires_module("maintenance")
PmStatus = Literal["OVERDUE", "DUE_SOON", "OK"]


class PlanIn(Strict):
    machine_id: UUID | None = None
    mould_id: UUID | None = None
    title: str = Field(min_length=3, max_length=120)
    interval_days: int | None = Field(default=None, gt=0, le=3650)
    interval_shots: int | None = Field(default=None, gt=0, le=1_000_000_000)

    @model_validator(mode="after")
    def check(self) -> "PlanIn":
        if (self.machine_id is None) == (self.mould_id is None):
            raise ValueError("Give either a machine or a mould")
        if self.interval_days is None and self.interval_shots is None:
            raise ValueError("Give an interval in days, in shots, or both")
        if self.interval_shots is not None and self.mould_id is None:
            raise ValueError("Shots count only for moulds")
        return self


class PlanPatch(Strict):
    title: str | None = Field(default=None, min_length=3, max_length=120)
    interval_days: int | None = Field(default=None, gt=0, le=3650)
    interval_shots: int | None = Field(default=None, gt=0, le=1_000_000_000)
    active: bool | None = None


class DoneIn(Strict):
    notes: str | None = Field(default=None, max_length=500)
    done_at: datetime | None = None  # when the work was done; defaults to now


class ShotsIn(Strict):
    shots: int = Field(gt=0, le=10_000_000)


class PlanOut(BaseModel):
    pm_plan_id: UUID
    unit_id: UUID
    machine_id: UUID | None
    mould_id: UUID | None
    equipment_code: str
    title: str
    interval_days: int | None
    interval_shots: int | None
    last_done_at: datetime | None
    next_due_at: datetime | None
    shots_left: int | None
    pm_status: PmStatus
    active: bool


class TaskOut(BaseModel):
    pm_task_id: UUID
    pm_plan_id: UUID
    due_at: datetime
    completed_at: datetime | None
    shots_at_done: int | None
    status: str
    notes: str | None


class MouldLife(BaseModel):
    mould_id: UUID
    code: str
    shots_done: int
    shots_limit: int | None
    life_used_pct: float | None
    over_limit: bool


PLAN_SQL = (
    "SELECT p.pm_plan_id, p.unit_id, p.machine_id, p.mould_id, COALESCE(m.code, t.code) AS "
    "equipment_code, p.title, p.interval_days, p.interval_shots, p.last_done_at, p.active, "
    "CASE WHEN p.interval_days IS NULL THEN NULL ELSE COALESCE(p.last_done_at, p.created_at) + "
    "make_interval(days => p.interval_days) END AS next_due_at, CASE WHEN p.interval_shots IS NULL "
    "THEN NULL ELSE p.interval_shots - (COALESCE(t.shots_done, 0) - p.last_done_shots) END AS "
    "shots_left FROM erp.pm_plan p LEFT JOIN erp.machine m ON m.machine_id = p.machine_id "
    "LEFT JOIN erp.mould t ON t.mould_id = p.mould_id"
)


def judge(row: dict[str, Any], soon_days: int, now: datetime) -> PmStatus:
    due, left, size = row["next_due_at"], row["shots_left"], row["interval_shots"]
    if (due is not None and due < now) or (left is not None and left <= 0):
        return "OVERDUE"
    if (due is not None and due < now + timedelta(days=soon_days)) or (
            left is not None and size and left <= size / 10):
        return "DUE_SOON"
    return "OK"


async def describe(ctx: Ctx, data: list[dict[str, Any]]) -> list[PlanOut]:
    soon = int(await rules.get_value(ctx, "pmDueSoonDays"))
    now = datetime.now(UTC)
    return [PlanOut(**d, pm_status=judge(d, soon, now)) for d in data]


async def load(ctx: Ctx, plan_id: UUID) -> PlanOut:
    row = await one(ctx, f"{PLAN_SQL} WHERE p.pm_plan_id = :id", {"id": plan_id})
    if row is None:
        raise not_found("Maintenance plan")
    require_in_scope(ctx, row["unit_id"])
    return (await describe(ctx, [row]))[0]


@router.post("/pm-plans", response_model=PlanOut, status_code=status.HTTP_201_CREATED)
async def create_plan(body: PlanIn, ctx: Ctx = Depends(manage)) -> PlanOut:
    table, key, ident = (("machine", "machine_id", body.machine_id) if body.machine_id
                         else ("mould", "mould_id", body.mould_id))
    target = await one(ctx, f"SELECT unit_id, active FROM erp.{table} WHERE {key} = :id",
                       {"id": ident})
    if target is None:
        raise HTTPException(422, f"The {table} does not exist")
    require_in_scope(ctx, target["unit_id"])
    if not target["active"]:
        raise HTTPException(422, f"The {table} is inactive")
    created = await one(
        ctx, "INSERT INTO erp.pm_plan(tenant_id, unit_id, machine_id, mould_id, title, "
        "interval_days, interval_shots, last_done_shots) VALUES (erp.current_tenant_id(), :u, "
        ":m, :t, :title, :d, :s, COALESCE((SELECT shots_done FROM erp.mould WHERE mould_id = :t), "
        "0)) RETURNING pm_plan_id",
        {"u": target["unit_id"], "m": body.machine_id, "t": body.mould_id, "title": body.title,
         "d": body.interval_days, "s": body.interval_shots})
    assert created is not None
    await audit(ctx, "pm_plan.create", "pm_plan", created["pm_plan_id"], body.model_dump())
    return await load(ctx, created["pm_plan_id"])


@router.patch("/pm-plans/{plan_id}", response_model=PlanOut)
async def update_plan(plan_id: UUID, body: PlanPatch, ctx: Ctx = Depends(manage)) -> PlanOut:
    current = await load(ctx, plan_id)
    days = body.interval_days if body.interval_days is not None else current.interval_days
    shots = body.interval_shots if body.interval_shots is not None else current.interval_shots
    if shots is not None and current.mould_id is None:
        raise HTTPException(422, "Shots count only for moulds")
    await rows(
        ctx, "UPDATE erp.pm_plan SET title = :t, interval_days = :d, interval_shots = :s, "
        "active = :a WHERE pm_plan_id = :id RETURNING pm_plan_id",
        {"t": body.title or current.title, "d": days, "s": shots,
         "a": current.active if body.active is None else body.active, "id": plan_id})
    await audit(ctx, "pm_plan.update", "pm_plan", plan_id, body.model_dump(exclude_none=True))
    return await load(ctx, plan_id)


@router.get("/pm-plans", response_model=Page[PlanOut])
async def list_plans(
    unit_id: UUID | None = None, pm_status: PmStatus | None = Query(None, alias="status"),
    machine_id: UUID | None = None, mould_id: UUID | None = None, active: bool | None = True,
    page: Paging = Depends(), ctx: Ctx = Depends(read),
) -> Page[PlanOut]:
    """The schedule: every plan with its next due date or shots left, overdue ones first."""
    conditions: list[str] = []
    params: dict[str, Any] = {}
    clause, scope_params = scope_clause(ctx, "p.unit_id")
    if clause:
        conditions.append(clause)
        params.update(scope_params)
    for text_, key, value in (
            ("p.unit_id = :u", "u", unit_id), ("p.machine_id = :m", "m", machine_id),
            ("p.mould_id = :t", "t", mould_id), ("p.active = :a", "a", active)):
        if value is not None:
            conditions.append(text_)
            params[key] = value
    where = f" WHERE {' AND '.join(conditions)}" if conditions else ""
    data = await rows(ctx, f"{PLAN_SQL}{where}", params)
    described = await describe(ctx, data)
    if pm_status is not None:
        described = [d for d in described if d.pm_status == pm_status]
    order = {"OVERDUE": 0, "DUE_SOON": 1, "OK": 2}
    described.sort(key=lambda d: (order[d.pm_status], d.next_due_at or datetime.max.replace(
        tzinfo=UTC), d.equipment_code))
    return Page(items=described[page.offset:page.offset + page.limit], total=len(described),
                limit=page.limit, offset=page.offset)


@router.get("/pm-plans/{plan_id}", response_model=PlanOut)
async def get_plan(plan_id: UUID, ctx: Ctx = Depends(read)) -> PlanOut:
    return await load(ctx, plan_id)


@router.post("/pm-plans/{plan_id}/done", response_model=PlanOut)
async def done(plan_id: UUID, body: DoneIn, ctx: Ctx = Depends(manage)) -> PlanOut:
    """Record the maintenance: it goes into the history and the next interval starts from it."""
    plan = await load(ctx, plan_id)
    if not plan.active:
        raise HTTPException(status.HTTP_409_CONFLICT, "The plan is inactive")
    when = body.done_at or datetime.now(UTC)
    if when > datetime.now(UTC):
        raise HTTPException(422, "The work cannot be done in the future")
    shots = None
    if plan.mould_id is not None:
        mould = await one(ctx, "SELECT shots_done FROM erp.mould WHERE mould_id = :id FOR UPDATE",
                          {"id": plan.mould_id})
        shots = mould["shots_done"] if mould else 0
    await rows(
        ctx, "INSERT INTO erp.pm_task(tenant_id, pm_plan_id, due_at, status, completed_at, "
        "owner_user_id, notes, shots_at_done) VALUES (erp.current_tenant_id(), :p, :due, 'DONE', "
        ":w, :me, :n, :s) RETURNING pm_task_id",
        {"p": plan_id, "due": plan.next_due_at or when, "w": when,
         "me": ctx.principal.profile.app_user_id, "n": body.notes, "s": shots})
    await rows(ctx, "UPDATE erp.pm_plan SET last_done_at = :w, last_done_shots = COALESCE(:s, "
               "last_done_shots) WHERE pm_plan_id = :id RETURNING pm_plan_id",
               {"w": when, "s": shots, "id": plan_id})
    await audit(ctx, "pm_plan.done", "pm_plan", plan_id, {"done_at": when, "notes": body.notes})
    return await load(ctx, plan_id)


@router.get("/pm-plans/{plan_id}/history", response_model=list[TaskOut])
async def history(plan_id: UUID, ctx: Ctx = Depends(read)) -> list[TaskOut]:
    await load(ctx, plan_id)
    data = await rows(ctx, "SELECT pm_task_id, pm_plan_id, due_at, completed_at, shots_at_done, "
                      "status, notes FROM erp.pm_task WHERE pm_plan_id = :id ORDER BY completed_at "
                      "DESC NULLS LAST, due_at DESC", {"id": plan_id})
    return [TaskOut(**d) for d in data]


# ------------------------------------------------------------------ mould shots and life
async def mould_life(ctx: Ctx, mould_id: UUID) -> MouldLife:
    row = await one(ctx, "SELECT mould_id, unit_id, code, shots_done, shots_limit FROM erp.mould "
                    "WHERE mould_id = :id", {"id": mould_id})
    if row is None:
        raise not_found("Mould")
    require_in_scope(ctx, row["unit_id"])
    limit = row["shots_limit"]
    return MouldLife(mould_id=row["mould_id"], code=row["code"], shots_done=row["shots_done"],
                     shots_limit=limit,
                     life_used_pct=round(row["shots_done"] * 100 / limit, 1) if limit else None,
                     over_limit=bool(limit and row["shots_done"] >= limit))


@router.post("/moulds/{mould_id}/shots", response_model=MouldLife)
async def add_shots(mould_id: UUID, body: ShotsIn, ctx: Ctx = Depends(record_shots)) -> MouldLife:
    """Add the shots a mould ran (production entry); plans and mould life follow from this."""
    await mould_life(ctx, mould_id)
    await rows(ctx, "UPDATE erp.mould SET shots_done = shots_done + :s WHERE mould_id = :id "
               "RETURNING mould_id", {"s": body.shots, "id": mould_id})
    await audit(ctx, "mould.shots", "mould", mould_id, {"shots": body.shots})
    return await mould_life(ctx, mould_id)


@router.get("/moulds/{mould_id}/life", response_model=MouldLife)
async def get_life(mould_id: UUID, ctx: Ctx = Depends(read)) -> MouldLife:
    return await mould_life(ctx, mould_id)


@router.get("/moulds-over-limit", response_model=list[MouldLife])
async def over_limit(unit_id: UUID | None = None, ctx: Ctx = Depends(read)) -> list[MouldLife]:
    """Moulds that have run past their shot limit and need replacing or refurbishing."""
    clause, params = scope_clause(ctx, "unit_id")
    conditions = ["active", "shots_limit IS NOT NULL", "shots_done >= shots_limit"]
    if clause:
        conditions.append(clause)
    if unit_id is not None:
        conditions.append("unit_id = :u")
        params["u"] = unit_id
    data = await rows(ctx, "SELECT mould_id FROM erp.mould WHERE " + " AND ".join(conditions)
                      + " ORDER BY code", params)
    return [await mould_life(ctx, d["mould_id"]) for d in data]

