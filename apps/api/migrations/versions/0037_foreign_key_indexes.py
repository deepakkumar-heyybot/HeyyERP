def name(table: str, column: str) -> str:
    return f"ix_{table}_{column}"[:63]


def upgrade() -> None:
    for table, column in INDEXES:
        op.execute(
            f"CREATE INDEX IF NOT EXISTS {name(table, column)} ON erp.{table} ({column})")


def downgrade() -> None:
    for table, column in INDEXES:
        op.execute(f"DROP INDEX IF EXISTS erp.{name(table, column)}")
